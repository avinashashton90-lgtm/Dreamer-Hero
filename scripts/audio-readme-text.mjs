// The text of public/audio/README.md (shared by audio-readme.mjs and the audio test).
import { SOUNDS, MUSIC, MUSIC_LAYERS, VOICES } from '../src/soundCatalog.js';
import { LINE_IDS } from '../src/soundscape.js';
import { CONFIG, DIALOGUE } from '../src/config.js';

export function buildAudioReadme() {
  const ext = CONFIG.audio.extensions;
  const L = [];
  L.push('# Sound files');
  L.push('');
  L.push('Every sound in Dreamer Hero has a name. Drop a file with the name below into this folder and the game');
  L.push(`plays it instead of its synthesized fallback (the game looks for \`.${ext[0]}\` first, then \`.${ext[1]}\`).`);
  L.push('Nothing else to change: the build lists the files it finds here (`virtual:audio-files` in `vite.config.js`;');
  L.push('restart `npm run dev` after adding files if the page does not reload by itself). A missing or broken file');
  L.push('never crashes the game; it just keeps the synthesized sound.');
  L.push('');
  L.push('Loops (↻) should loop seamlessly. Short effects work best trimmed tight, mono, 44.1 or 48 kHz.');
  L.push('Volumes are mixed in code (three groups: music, effects, voices — see `CONFIG.audio`).');
  L.push('');
  L.push('_This file is generated by `npm run audio:readme` from `src/soundCatalog.js` and the dialogue in `src/config.js`._');
  L.push('');
  L.push('## Music (`music_<track>`)');
  L.push('');
  L.push('| Section | File | Description |');
  L.push('|---|---|---|');
  const tracks = new Set();
  for (const [name, m] of Object.entries(MUSIC)) {
    const file = tracks.has(m.track) ? `(uses music_${m.track})` : `music_${m.track}.${ext[0]}`;
    tracks.add(m.track);
    L.push(`| ${name} | ${file} | ${m.desc} |`);
  }
  for (const [name, l] of Object.entries(MUSIC_LAYERS)) L.push(`| layer: ${name} | ${name === 'wind' ? `music_chase_wind.${ext[0]}` : `music_boss_${name}.${ext[0]}`} | ${l.desc} |`);
  L.push('');
  L.push('Layer files only play over a music file of their track (they start together, so give them the same length).');
  L.push('');
  L.push('## Sound effects');
  L.push('');
  L.push('| Name | File | Description |');
  L.push('|---|---|---|');
  for (const [name, s] of Object.entries(SOUNDS)) if (s.group === 'effects') L.push(`| ${name}${s.loop ? ' ↻' : ''} | ${name}.${ext[0]} | ${s.desc} |`);
  L.push('');
  L.push('## Voice efforts');
  L.push('');
  L.push('| Name | File | Description |');
  L.push('|---|---|---|');
  for (const [name, s] of Object.entries(SOUNDS)) if (s.group === 'voices') L.push(`| ${name} | ${name}.${ext[0]} | ${s.desc} |`);
  L.push('');
  L.push('## Voice lines (`voice/<character>_<line>`)');
  L.push('');
  L.push('Without a file, each line plays a short synthesized "talking" blip per character as the text types out');
  L.push(`(${Object.entries(VOICES).map(([id, v]) => `${id}: ${v.desc}`).join(', ')}).`);
  L.push('');
  L.push('| File | Speaker | Line |');
  L.push('|---|---|---|');
  const speakerOf = speakerMap();
  for (const [text, id] of LINE_IDS) {
    const who = speakerOf.get(text) ?? 'aj';
    L.push(`| voice/${who}_${id}.${ext[0]} | ${who} | ${text.replace(/\|/g, '\\|')} |`);
  }
  L.push('');
  return L.join('\n');
}

/** Who says each line (from the cutscene scripts: hero → aj, girl → amy). */
function speakerMap() {
  const who = new Map();
  const G = DIALOGUE.girlScene;
  const P = DIALOGUE.pitScene;
  const P2 = DIALOGUE.part2;
  const aj = [G.safe, G.safety, P.keepGoing, P.ok, P.who, P2.portal.amy, P2.arrival.where, P2.arrival.amy];
  const amy = [G.thanks, G.castle, P.stop, P.notWell, P.water, P.drink, P2.portal.thanks, P2.portal.wait];
  const tick = [P2.arrival.welcome, P2.arrival.stops, P2.arrival.witch, P2.arrival.cannot];
  for (const t of aj) who.set(t, 'aj');
  for (const t of amy) who.set(t, 'amy');
  for (const t of tick) who.set(t, 'tick');
  return who;
}
